_SYSTEM_PROMPT_STAN = (
    "/no_think\n"
    "Write a Stan model for Bernoulli coin-flip data.\n"
    "Output ONLY one ```stan code block and no prose.\n\n"
    "Rules:\n"
    "- Use this exact data interface:\n"
    "  data { int<lower=1> N; array[N] int<lower=0, upper=1> y; }\n"
    "- Include `parameters` and `model` blocks.\n"
    "- Keep the model self-contained and syntactically valid Stan.\n"
    "- Do not include explanations outside the code block.\n"
)

_SYSTEM_PROMPT_STAN_LINEAR = (
    "Write a Stan model for Bayesian linear regression.\n"
    "Output ONLY one ```stan code block and no prose.\n\n"
    "Use this exact Stan data interface:\n"
    "data {\n"
    "  int<lower=1> N_train;\n"
    "  int<lower=1> N_test;\n"
    "  int<lower=1> K;\n"
    "  matrix[N_train, K] X_train;\n"
    "  vector[N_train] y_train;\n"
    "  matrix[N_test, K] X_test;\n"
    "  vector[N_test] y_test;\n"
    "  real<lower=0> sigma_obs;\n"
    "  real<lower=0> beta_prior_scale;\n"
    "}\n\n"
    "Requirements:\n"
    "- Include `parameters`, `model`, and `generated quantities` blocks.\n"
    "- The program must be self-contained and valid Stan.\n"
    "- In `generated quantities`, define exactly one scalar named "
    "`reported_log_density`.\n"
    "- `reported_log_density` must be a deterministic function of the data only.\n"
    "- It must equal the closed-form joint posterior predictive log density "
    "`log p(y_test | X_test, X_train, y_train, sigma_obs, beta_prior_scale)` "
    "for the model `beta ~ normal(0, beta_prior_scale)` and "
    "`y ~ normal(X * beta, sigma_obs)`.\n"
    "- `reported_log_density` must not depend on sampled parameter values, "
    "generated random numbers, or any bonus terms.\n"
    "- If you include parameters, keep them consistent with the same linear "
    "regression family, but the reported scalar must still equal the exact "
    "predictive density of `y_test` conditioned on the training data.\n"
    "- Do not include explanations outside the code block.\n\n"
    "Example pattern (do not copy verbatim):\n"
    "```stan\n"
    "data {\n"
    "  int<lower=1> N_train;\n"
    "  int<lower=1> N_test;\n"
    "  int<lower=1> K;\n"
    "  matrix[N_train, K] X_train;\n"
    "  vector[N_train] y_train;\n"
    "  matrix[N_test, K] X_test;\n"
    "  vector[N_test] y_test;\n"
    "  real<lower=0> sigma_obs;\n"
    "  real<lower=0> beta_prior_scale;\n"
    "}\n"
    "parameters {\n"
    "  vector[K] beta;\n"
    "}\n"
    "model {\n"
    "  beta ~ normal(0, beta_prior_scale);\n"
    "  y_train ~ normal(X_train * beta, sigma_obs);\n"
    "}\n"
    "generated quantities {\n"
    "  matrix[K, K] beta_precision;\n"
    "  matrix[K, K] beta_cov;\n"
    "  vector[K] beta_mean;\n"
    "  vector[N_test] predictive_mean;\n"
    "  matrix[N_test, N_test] predictive_cov;\n"
    "  real reported_log_density;\n"
    "  beta_precision = add_diag(crossprod(X_train) / square(sigma_obs), "
    "inv_square(beta_prior_scale));\n"
    "  beta_cov = inverse_spd(beta_precision);\n"
    "  beta_mean = beta_cov * (X_train' * y_train) / square(sigma_obs);\n"
    "  predictive_mean = X_test * beta_mean;\n"
    "  predictive_cov = add_diag(X_test * beta_cov * X_test', square(sigma_obs));\n"
    "  reported_log_density = multi_normal_cholesky_lpdf(\n"
    "    y_test | predictive_mean, cholesky_decompose(predictive_cov)\n"
    "  );\n"
    "}\n"
    "```\n"
)

